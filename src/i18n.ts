export const localeStorageKey = "safehands.locale";

export function isLocale(value: unknown): value is Locale {
  return LOCALE_OPTIONS.some((option) => option.code === value);
}

export function getSavedLocale(): Locale | null {
  try {
    const value = globalThis.localStorage?.getItem(localeStorageKey);
    return isLocale(value) ? value : null;
  } catch {
    return null;
  }
}

export function saveLocale(locale: Locale): void {
  try {
    globalThis.localStorage?.setItem(localeStorageKey, locale);
  } catch {
    // Private browsing and restricted web views can reject localStorage.
  }
}

export function t(locale: Locale, key: MessageKey, values?: Record<string, string | number>): string {
  const template = localeMessages[locale]?.[key] ?? localeMessages.en[key] ?? key;
  if (!values) return template;
  return Object.entries(values).reduce(
    (text, [name, value]) => text.split(`{{${name}}}`).join(String(value)),
    template,
  );
}

