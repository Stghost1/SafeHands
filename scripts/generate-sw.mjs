import { cpSync, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const root = process.cwd();
const dist = join(root, "dist");

function copy(source, destination) {
  mkdirSync(join(dist, destination, ".."), { recursive: true });
  cpSync(join(root, source), join(dist, destination), { recursive: true });
}

copy("src/data/triage-protocol.json", "data/triage-protocol.json");
copy("src/data/facilities.json", "data/facilities.json");
copy("src/data/scam-fixtures.json", "data/scam-fixtures.json");
copy("src/data/climate-protocols.json", "data/climate-protocols.json");
copy("src/data/authority-directory.json", "data/authority-directory.json");
copy("src/data/locales", "data/locales");

function filesUnder(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const absolute = join(directory, entry.name);
    if (entry.isDirectory()) return filesUnder(absolute);
    return [absolute];
  });
}

const assets = filesUnder(dist)
  .filter((file) => !file.endsWith(`${sep}sw.js`))
  .map((file) => `./${relative(dist, file).split(sep).join("/")}`)
  .sort();

const worker = `/* Generated by scripts/generate-sw.mjs. Keep this file same-origin and offline-only. */
const CACHE_NAME = "safehands-shell-v1";
const APP_SHELL = ${JSON.stringify(["./", ...assets], null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => Promise.all(APP_SHELL.map((url) => cache.add(url).catch(() => undefined))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;
  event.respondWith(
    caches.match(request).then((cached) => cached || fetch(request)
      .then((response) => {
        if (response.ok) void caches.open(CACHE_NAME).then((cache) => cache.put(request, response.clone()));
        return response;
      })
      .catch(() => request.mode === "navigate" ? caches.match("./index.html") : Response.error())),
  );
});
`;

writeFileSync(join(dist, "sw.js"), worker, "utf8");
console.log(`Generated offline service worker with ${assets.length} cached assets.`);
